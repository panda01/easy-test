import { useCallback, useState } from "react";
import { useRecordListWithAdditions } from "./useRecordListWithAdditions";
import { type ActionPlan } from "../utils/actionPlanSteps";
import { actionScriptsApiUrl } from "../utils/routePaths";

/**
 * A version's newest run, cut down to what its status line needs: whether it
 * passed and, when it failed, at which step or by timing out. The API reads
 * it from the run's own row.
 */
export interface LatestActionScriptRunRecord {
  /** The run's cuid. */
  id: string;
  /** True when the run passed. */
  succeeded: boolean;
  /** The 1-based step the run stopped at, or null when it passed or stopped before the first step. */
  failedStepNumber: number | null;
  /** True when the run hit the time limit and was stopped. */
  timedOut: boolean;
  /** When the run was recorded. */
  createdAt: string;
}

/** The parts of a recorded run `recordFinishedRun` needs: which version it ran, and how it went. */
export type FinishedActionScriptRun = LatestActionScriptRunRecord & {
  /** The version that was run. */
  actionScriptId: string;
};

/**
 * The failed run a version was refined from, as the API joins it onto the
 * refinement: read from the run's own row, never copied onto the refinement.
 */
export interface RefinedActionScriptRunSummary {
  /** The run's cuid. */
  id: string;
  /** Why the run stopped, or null (a refined run always failed, so this is normally set). */
  errorMessage: string | null;
  /** The 1-based step the run stopped at, or null when it stopped before the first step. */
  failedStepNumber: number | null;
  /** True when the run hit the time limit and was stopped. */
  timedOut: boolean;
  /** The failing page's aria snapshot, or null when none was captured - Claude was sent it whenever it is set. */
  failingPageAriaSnapshot: string | null;
}

/**
 * How a version was made by refining a failed run of an earlier version: the
 * facts stored only here (the user's note, what the refine call cost, whether
 * the failure screenshot was sent) plus the failed run's summary. The model
 * and effort are the refined version's own `modelId` and `effort`.
 */
export interface ActionScriptRefinementRecord {
  id: string;
  websiteId: string;
  actionId: string;
  /** The version whose failed run was refined. */
  sourceActionScriptId: string;
  /** The failed run that was refined. */
  actionScriptRunId: string;
  /** The version the refinement produced (the one carrying this record). */
  refinedActionScriptId: string;
  /** The note the user gave Claude, or null when they gave none. */
  note: string | null;
  /** Input tokens the refine call used (not counting cache reads or writes). */
  inputTokens: number;
  /** Output tokens the refine call used. */
  outputTokens: number;
  /** Input tokens read from the prompt cache. */
  cacheReadInputTokens: number;
  /** Input tokens written to the prompt cache. */
  cacheCreationInputTokens: number;
  /** True when the failure screenshot was sent to Claude (false when the run had none, or its file was missing). */
  screenshotWasSent: boolean;
  createdAt: string;
  updatedAt: string;
  deletedAt: string | null;
  /** The failed run, read from its own row. */
  actionScriptRun: RefinedActionScriptRunSummary;
}

/**
 * One saved plan version for an action, as the API returns it - generated by
 * Claude ("Convert to script"), refined by Claude from a failed run
 * ("Refine"), or saved from the step editor. Versions are immutable:
 * converting, refining, or editing again creates a new one. Dates arrive as
 * ISO strings because they travel as JSON. Declared here rather than imported
 * from the server: the client never imports server code.
 */
export interface ActionScriptRecord {
  id: string;
  websiteId: string;
  actionId: string;
  /** The website's name when the script was generated. */
  websiteName: string;
  /** The website's URL when the plan was generated. */
  startUrl: string;
  /** The action's title when the script was generated. */
  actionTitle: string;
  /** The action's description when the script was generated. */
  actionDescription: string;
  /** The credential the action ran as when the plan was generated, or null for logged out. */
  credentialId: string | null;
  /** That credential's name then, or null for logged out. */
  credentialName: string | null;
  /** Claude's one-line summary of what the plan does. */
  summary: string;
  /** The assumptions Claude made where the action was ambiguous. */
  assumptions: string[];
  /** The step plan. */
  plan: ActionPlan;
  /** The crawled pages whose aria snapshots Claude was shown. */
  contextPageUrls: string[];
  /** The model that wrote (or refined) the plan (the fallback's id when the chosen model declined), or null for an edited version. */
  modelId: string | null;
  /** The effort level sent, or null: "Standard" for a model with no effort setting, or an edited version. */
  effort: string | null;
  /** The version this one was edited from, or null for a generated or refined version. */
  editedFromActionScriptId: string | null;
  /** How this version was refined from a failed run, or null when it was not refined. */
  refinement: ActionScriptRefinementRecord | null;
  /** This version's newest run, or null when it has not been run yet. */
  latestRun: LatestActionScriptRunRecord | null;
  createdAt: string;
  updatedAt: string;
  deletedAt: string | null;
}

/** What `useActionScripts` hands back. */
export interface ActionScriptsState {
  /** Every saved version, newest first, each with its newest run - including a run recorded on this visit. */
  scripts: ActionScriptRecord[];
  /** True until the script list for the current action has arrived. */
  isLoading: boolean;
  /** Why the script list could not be fetched, or null. */
  errorMessage: string | null;
  /** Adds a version a "Convert to script", "Refine", or "Save as new version" POST just saved to the front of `scripts`. */
  addCreatedScript: (createdScript: ActionScriptRecord) => void;
  /** Makes a run a "Run script" POST just recorded its version's `latestRun`, so its status shows without refetching. */
  recordFinishedRun: (finishedRun: FinishedActionScriptRun) => void;
}

/**
 * Fetches an action's saved script versions
 * (`GET /api/websites/:websiteId/actions/:actionId/scripts`), newest first,
 * and lets the page add the version a "Convert to script", "Refine", or
 * "Save as new version" POST just saved without refetching.
 *
 * It also lets the page record a run a "Run script" POST just finished: that
 * run replaces its version's `latestRun` for the rest of the visit (a run
 * recorded now is always newer than the one the list was fetched with), so
 * the versions list shows the new pass / fail status at once.
 * @param websiteId - The owning website's cuid
 * @param actionId - The action's cuid
 * @returns The scripts, the list request's state, `addCreatedScript`, and `recordFinishedRun`
 */
export function useActionScripts(websiteId: string, actionId: string): ActionScriptsState {
  const [latestRunRecordedThisVisitByScriptId, setLatestRunRecordedThisVisitByScriptId] =
    useState<ReadonlyMap<string, LatestActionScriptRunRecord>>(() => new Map());

  const recordFinishedRun = useCallback((finishedRun: FinishedActionScriptRun): void => {
    const { actionScriptId, id, succeeded, failedStepNumber, timedOut, createdAt } = finishedRun;
    setLatestRunRecordedThisVisitByScriptId((previousLatestRuns) =>
      new Map(previousLatestRuns).set(actionScriptId, {
        id,
        succeeded,
        failedStepNumber,
        timedOut,
        createdAt,
      }),
    );
  }, []);

  /**
   * Keeps an added script only while it belongs to the action shown.
   * @param script - A script added on this visit
   * @returns True when it belongs to the current action
   */
  const scriptBelongsToThisAction = (script: ActionScriptRecord): boolean =>
    script.actionId === actionId;

  const scriptList = useRecordListWithAdditions<ActionScriptRecord>(
    actionScriptsApiUrl(websiteId, actionId),
    scriptBelongsToThisAction,
  );

  /**
   * Gives a version the run recorded for it on this visit, when there is one.
   * @param script - A listed version
   * @returns The version with that run as its `latestRun`, or the version unchanged
   */
  const withLatestRunRecordedThisVisit = (script: ActionScriptRecord): ActionScriptRecord => {
    const latestRunRecordedThisVisit = latestRunRecordedThisVisitByScriptId.get(script.id);
    const scriptWasRunThisVisit = latestRunRecordedThisVisit !== undefined;
    return scriptWasRunThisVisit ? { ...script, latestRun: latestRunRecordedThisVisit } : script;
  };

  return {
    scripts: scriptList.records.map(withLatestRunRecordedThisVisit),
    isLoading: scriptList.isLoading,
    errorMessage: scriptList.errorMessage,
    addCreatedScript: scriptList.addRecord,
    recordFinishedRun,
  };
}
